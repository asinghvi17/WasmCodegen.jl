# Wasm-only lowering and multivalue/JavaScript adapter.
struct LoweredProgram
    spec::ProgramSpec
    mod::Module
    state_type::DataType
    source::String
end
latest(m, name) = Base.invokelatest(getglobal, m, name)
function lower(spec::ProgramSpec)
    states = validate_states(spec, [spec.setup(spec.config) for _ in 1:spec.instances.capacity])
    S = eltype(states)
    m = Module(gensym(:BuiltProgram))
    for (name, value) in [(:STATES, states), (:GENERATIONS, fill(UInt32(1),length(states))),
                          (:ACTIVE, fill(false,length(states))), (:RESET,spec.reset)]
        Core.eval(m, :(const $name = $value))
    end
    for (j,e) in enumerate(spec.exports)
        name = Symbol("OP_",j)
        Core.eval(m, :(const $name = $(e.f)))
    end
    source = kernel_source(spec)
    Core.eval(m, Meta.parseall(source))
    LoweredProgram(spec,m,S,source)
end
wasmtype(T) = T in (Int32, UInt32) ? "i32" : T in (Int64, UInt64) ? "i64" :
              T === Float32 ? "f32" : "f64"
signature(name, args, R) = (; name, args=String[string(T) for T in args],
    returns=["Int32", string(R)], wasm_args=String[wasmtype(T) for T in args],
    wasm_returns=["i32", wasmtype(R)])

function wasm_manifest(spec)
    exports = [signature("create", (), UInt64), signature("destroy", (UInt64,), Int32)]
    append!(exports, [signature(string(e.name), (UInt64,e.argtypes...), e.returns)
                      for e in spec.exports])
    (; wasm_gc=(; exports, exceptions="propagate as Wasm exceptions/traps"))
end

function loader(p::LoweredProgram, wasmfile)
    methods = String[]
    for e in p.spec.exports
        # Computed property names support Julia identifiers that are JS keywords.
        call = "this.#call($(JSON.json(string(e.name))), args)"
        value = e.returns === UInt32 ? "($call >>> 0)" :
                e.returns === UInt64 ? "BigInt.asUintN(64, $call)" : call
        push!(methods, "  [$(JSON.json(string(e.name)))](...args) { return $value; }")
    end
    return """
    // Generated by ProgramBuild. UInt64 handles and i64 values use BigInt.
    import { readFile } from 'node:fs/promises';
    import { randomFillSync } from 'node:crypto';
    export class ProgramError extends Error {
      constructor(operation, status) {
        super(`\${operation} failed (status \${status})`);
        this.status = status;
      }
    }
    const checked = (operation, result) => {
      const [status, value] = result;
      if (status !== 0) throw new ProgramError(operation, status);
      return value;
    };
    export async function load(imports = {}) {
      const bytes = await readFile(new URL($(JSON.json(wasmfile)), import.meta.url));
      const julia = {
        write_byte: (fd, b) => process[fd === 2 ? 'stderr' : 'stdout'].write(Buffer.from([b])),
        entropy: () => BigInt.asIntN(64, randomFillSync(new BigUint64Array(1))[0]),
        hrtime: () => process.hrtime.bigint(),
        ...imports.julia,
      };
      const { instance } = await WebAssembly.instantiate(bytes, { ...imports, julia });
      const raw = instance.exports;
      class Handle {
        #handle;
        constructor() {
          this.#handle = BigInt.asUintN(64, checked('create', raw.create()));
        }
        get handle() { return this.#handle; }
        #call(name, args) { return checked(name, raw[name](this.#handle, ...args)); }
    $(join(methods, "\n"))
        destroy() {
          checked('destroy', raw.destroy(this.#handle));
          this.#handle = 0n;
        }
      }
      return { Handle, raw, instance };
    }
    """
end


function build(spec::ProgramSpec, ::WasmGC; output_dir)
    @eval import WasmCodegen
    Base.invokelatest(build_wasm, lower(spec), output_dir)
end
function build_wasm(p, dir)
    mkpath(dir)
    entries = [WasmCodegen.Entry(latest(p.mod,:create),();name="create"),
               WasmCodegen.Entry(latest(p.mod,:destroy),(UInt64,);name="destroy")]
    append!(entries, [WasmCodegen.Entry(latest(p.mod,Symbol("export_",e.name)),
                       (UInt64,e.argtypes...); name=string(e.name)) for e in p.spec.exports])
    result = @timed WasmCodegen.with_trim_patches() do _, _
        WasmCodegen.compile(entries; config=WasmCodegen.Config(verify=:error,
            trim=:safe, on_unsupported=:error))
    end
    c = result.value
    stem = p.spec.name
    write(joinpath(dir,stem*".wasm"),c.bytes)
    write(joinpath(dir,stem*".mjs"),loader(p,stem*".wasm"))
    write(joinpath(dir,stem*"-wasm-wrappers.jl"),p.source)
    write_manifest(p.spec,wasm_manifest(p.spec),dir)
    stats = (; bytes=length(c.bytes), compile_seconds=result.time,
        functions=length(c.cgm.funcs), serialized_objects=length(c.cgm.image.globals),
        trim_report=c.world.trim_report[],diagnostics=length(c.cgm.diagnostics),trim="safe")
    write(joinpath(dir,stem*"-wasm-stats.json"),JSON.json(stats))
    (; compilation=c,stats)
end
