# Generates operators_data.jl, the parser's operator tables (Julia's flisp front end,
# src/julia-parser.scm), as the running Julia has them:
#     julia src/runtime/gen_operators.jl
# Not included in the package: its output is.
const OUT = joinpath(@__DIR__, "operators_data.jl")
scm = """
(define (b x) (if x 1 0))
(for-each (lambda (o)
  (display "OP\\t") (display (string o)) (display "\\t")
  (display (b (operator? o))) (display "\\t") (display (b (no-suffix? o))) (display "\\t") (display (b (unary-op? o))) (display "\\t")
  (display (b (unary-and-binary-op? o))) (display "\\t") (display (b (syntactic-op? o))) (display "\\t")
  (display (operator-precedence o)) (newline))
  (delete-duplicates (append operators syntactic-operators unary-ops unary-and-binary-ops
                            (apply append (map eval prec-names)))))
"""
julia = joinpath(Sys.BINDIR, Base.julia_exename())
out = read(pipeline(`$julia --lisp`; stdin=IOBuffer(scm)), String)
rows = [split(m[1], '\t') for m in eachmatch(r"OP\t([^\n]*)", out)]
isempty(rows) && error("no operators from julia --lisp")
ops = String[]; nosuffix = String[]; unary = String[]; unarybin = String[]; syntactic = String[]
prec = Pair{String,Int}[]
for r in rows
    op = String(r[1])
    r[2] == "1" && push!(ops, op)
    r[3] == "1" && push!(nosuffix, op)
    r[4] == "1" && push!(unary, op)
    r[5] == "1" && push!(unarybin, op)
    r[6] == "1" && push!(syntactic, op)
    p = parse(Int, r[7]); p != 0 && push!(prec, op => p)
end
# operator suffix characters other than combining marks (which jl_op_suffix_char accepts by
# category): primes, sub- and superscripts (src/flisp/julia_opsuffs.h)
ismark(c) = Base.Unicode.category_code(Char(c)) in (Base.Unicode.UTF8PROC_CATEGORY_MN,
             Base.Unicode.UTF8PROC_CATEGORY_MC, Base.Unicode.UTF8PROC_CATEGORY_ME)
suffs = UInt32[c for c in 0xa1:0x10ffff if !(0xd800 <= c <= 0xdfff) &&
               ccall(:jl_op_suffix_char, Cint, (UInt32,), c) != 0 && !ismark(c)]
open(OUT, "w") do io
    println(io, "# Generated by gen_operators.jl from Julia ", VERSION, "'s parser: do not edit. (Candidates: see\n# `operators.jl`.)")
    str(v) = join((repr(x) for x in v), ", ")
    println(io, "const OPERATOR_LIST = String[", str(ops), "]")
    println(io, "const NO_SUFFIX_LIST = String[", str(nosuffix), "]")
    println(io, "const UNARY_LIST = String[", str(unary), "]")
    println(io, "const UNARY_AND_BINARY_LIST = String[", str(unarybin), "]")
    println(io, "const SYNTACTIC_LIST = String[", str(syntactic), "]")
    println(io, "const PRECEDENCE_LIST = Pair{String,Int}[", join(("$(repr(a)) => $b" for (a, b) in prec), ", "), "]")
    println(io, "const OP_SUFFIX_CHARS = UInt32[", join(("0x" * string(c, base=16, pad=4) for c in suffs), ", "), "]")
end
println("wrote ", OUT, ": ", length(ops), " operators, ", length(suffs), " suffix chars")
