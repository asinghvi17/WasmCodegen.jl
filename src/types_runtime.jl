# Run-time type information: predicates testing type ids against abstract types, generated
# once the module is complete (when all the concrete types of the closed world have ids).

"""
    isa_predicate!(cgm, T) -> Func

The function `(typeid::i32) -> i32` testing whether a type id is that of a subtype of
`T`. Its body is generated by [`finish_types!`](@ref).
"""
function isa_predicate!(cgm::CGModule, @nospecialize(T))
    get!(cgm.helpers, (:isa, T)) do
        add_func!(cgm.mod, string("jl_isa_", replace(string(T), r"[^A-Za-z0-9_]" => "_")),
                  ValType[I32], ValType[I32])
    end
end

function finish_types!(cgm::CGModule)
    for (key, f) in cgm.helpers
        key isa Tuple && key[1] === :isa || continue
        T = key[2]
        ids = Int32[id for (S, id) in cgm.types.typeids if S <: T]
        b = Builder(cgm.mod, f)
        if isempty(ids)
            emit!(b, :i32_const, 0)
        else
            for (i, id) in enumerate(sort(ids))
                emit!(b, :local_get, 0)
                emit!(b, :i32_const, id)
                emit!(b, :i32_eq)
                i > 1 && emit!(b, :i32_or)
            end
        end
        finish!(b)
    end
end

"""
    object_hash_func!(cgm) -> Func

The function `(obj::\$JlValue) -> i32` returning the identity hash of an object, assigned
on first use from a counter (the `hash` field of the header; 0 means unassigned).
"""
function object_hash_func!(cgm::CGModule)
    get!(cgm.helpers, :object_hash) do
        ts = cgm.types
        counter = add_global!(cgm.mod, "jl_hash_counter", I32, true, Inst[Inst(:i32_const, 0)])
        f = add_func!(cgm.mod, "jl_object_hash", ValType[jlvalue_ref(ts)], ValType[I32])
        b = Builder(cgm.mod, f)
        emit!(b, :local_get, 0)
        emit!(b, :struct_get, ts.jlvalue, 1)
        emit!(b, :i32_eqz)
        if!(b)
        emit!(b, :local_get, 0)
        emit!(b, :global_get, counter)
        emit!(b, :i32_const, 1)
        emit!(b, :i32_add)
        emit!(b, :global_set, counter)
        emit!(b, :global_get, counter)
        emit!(b, :struct_set, ts.jlvalue, 1)
        end!(b)
        emit!(b, :local_get, 0)
        emit!(b, :struct_get, ts.jlvalue, 1)
        finish!(b)
        f
    end
end

"Push the identity hash (an i32) of the object `x`."
function push_object_hash!(fc::FnCtx, x::CGVal)
    push_val!(fc, x)
    call!(fc.b, object_hash_func!(fc.cgm))
end

"""
Memory has no address on Wasm: each Memory object gets a virtual range of addresses, from
its identity hash shifted by 32 bits, so that the pointer comparisons Base makes (alias
checks, `dataids`) work. Pointers cannot be dereferenced.
"""
function push_memory_base!(fc::FnCtx, mem::CGVal)
    push_object_hash!(fc, mem)
    emit!(fc.b, :i64_extend_i32_u)
    emit!(fc.b, :i64_const, 32)
    emit!(fc.b, :i64_shl)
end
